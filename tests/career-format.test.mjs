// Role heads and the education block come from ../job-hunter/data/career.json
// through scripts/sync-career.mjs. These tests pin the formats.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { headLine, educationBlock, applyCareer } from '../scripts/lib/career-format.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const canonPath = join(root, '..', 'job-hunter', 'data', 'career.json');
const hasCanon = existsSync(canonPath);
const EM_DASH = String.fromCharCode(0x2014);

const fixture = {
  roles: [
    { id: 'att', section: 'experience', title: 'Lead Product Designer', company: 'AT&T', start: '2021-09', end: null },
    { id: 'ge', section: 'experience', title: 'UX Lead', company: 'GE Nuclear (via Kraybill)', start: '2012-11', end: '2016-06' },
    { id: 'nortel', section: 'earlier', title: 'Senior Web Designer', company: 'Nortel', start: '1996', end: '1996', surfaces: { retro: false, hub: false, mcp: false } },
  ],
  education: { degree: 'B.A.', school: 'Hardin-Simmons University', location: 'Abilene, Texas', coursework: '1988-1992', conferred: '2025-12-15' },
  earlier_education: [{ school: 'Samford University', location: 'Birmingham, Alabama', label: 'Freshman year' }],
  certifications: [
    { name: 'AI Strategy', issuer: 'Cornell University (eCornell)', years: '2025-2026' },
    { name: 'AI for Business Productivity', issuer: 'Cornell University (eCornell)', years: '2025-2026' },
    { name: 'AI Applications and Value Creation', issuer: 'Cornell University (eCornell)', years: '2025-2026' },
  ],
  salary: { text: '$190,000 to $230,000' },
};

const EXPECTED_EDUCATION = [
  '          <p>Education: BA Hardin-Simmons (Abilene, TX). Freshman year at Samford University (Birmingham, AL).</p>',
  '          <p>eCornell AI certificates 2025-2026: AI Strategy, AI for Business Productivity, AI Applications and Value Creation.</p>',
].join('\n');

const role = (id, head) => `          <div class="career-role" data-role="${id}" onclick="toggleRole(this)">\n            ${head}\n            <div class="career-body">Prose for ${id}.</div>\n          </div>`;
const page = (heads) => [
  '<div class="career-list">',
  ...heads,
  '</div>',
  '        <div class="about-section">',
  '          <!-- CAREER FACTS (generated by scripts/sync-career.mjs; do not edit by hand) -->',
  '          <p>Education: stale.</p>',
  '          <!-- /CAREER FACTS -->',
  '        </div>',
].join('\n');

test('experience heads carry years, earlier heads none', () => {
  assert.equal(headLine(fixture.roles[0]),
    '<div class="career-head"><strong>Lead Product Designer</strong><span>AT&amp;T, 2021 - Present</span></div>');
  assert.match(headLine({ section: 'experience', title: 'UX Innovation Lead', company: 'Citi (via C2G)', start: '2016-07', end: '2016-10' }), /Citi \(via C2G\), 2016<\/span>/);
  assert.match(headLine({ section: 'experience', title: 'Founder and Designer', company: 'Independent products', start: '2025', end: null }), /Independent products, 2025 - Present<\/span>/);
  assert.match(headLine(fixture.roles[1]), /GE Nuclear \(via Kraybill\), 2012 - 2016<\/span>/);
  assert.match(headLine(fixture.roles[2]), /<span>Nortel<\/span>/);
});

test('education block is exact', () => {
  assert.equal(educationBlock(fixture), EXPECTED_EDUCATION);
});

test('an unmapped state or mixed certificate years throw', () => {
  assert.throws(() => educationBlock({ ...fixture, education: { ...fixture.education, location: 'Austin, Ohio' } }), /no abbreviation for Ohio/);
  const certs = [...fixture.certifications.slice(0, 2), { ...fixture.certifications[2], years: '2026' }];
  assert.throws(() => educationBlock({ ...fixture, certifications: certs }), /certificates differ/);
});

test('applyCareer rewrites heads and the education block, and is idempotent', () => {
  const html = page([role('att', '<div class="career-head"><strong>Old</strong><span>AT&amp;T, 2020 - Present</span></div>'),
    role('ge', '<div class="career-head"><strong>UX Lead</strong><span>GE, 2012 - 2016</span></div>')]);
  const once = applyCareer(html, fixture);
  assert.ok(once.html.includes('<strong>Lead Product Designer</strong><span>AT&amp;T, 2021 - Present</span>'));
  assert.ok(once.html.includes(EXPECTED_EDUCATION));
  assert.ok(once.html.includes('Prose for att.'));
  assert.equal(applyCareer(once.html, fixture).html, once.html);
});

test('applyCareer reports a shown role with no block, and a hidden role with one', () => {
  const html = page([role('att', '<div class="career-head"><strong>x</strong><span>y</span></div>'),
    role('nortel', '<div class="career-head"><strong>x</strong><span>y</span></div>')]);
  const r = applyCareer(html, fixture);
  assert.deepEqual(r.missing, ['ge']);
  assert.deepEqual(r.hidden, ['nortel']);
});

test('a block without a head line is reported, and the next block keeps its head', () => {
  const headless = '          <div class="career-role" data-role="newrole" onclick="toggleRole(this)">\n            <div class="career-body">New.</div>\n          </div>';
  const html = page([headless,
    role('att', '<div class="career-head"><strong>Lead Product Designer</strong><span>AT&amp;T, 2021 - Present</span></div>'),
    role('ge', '<div class="career-head"><strong>UX Lead</strong><span>GE Nuclear (via Kraybill), 2012 - 2016</span></div>')]);
  const canon = { ...fixture, roles: [{ id: 'newrole', section: 'experience', title: 'Design Director', company: 'NewCo', start: '2026', end: null }, ...fixture.roles] };
  const r = applyCareer(html, canon);
  assert.deepEqual(r.headless, ['newrole']);
  assert.ok(r.html.includes('<strong>Lead Product Designer</strong><span>AT&amp;T, 2021 - Present</span>'));
  assert.ok(!r.html.includes('NewCo'));
});

test('a location without a state says what it needs', () => {
  assert.throws(() => educationBlock({ ...fixture, education: { ...fixture.education, location: 'London' } }), /location needs "City, State": London/);
});

test('escaping is plain: a canon entity shows as typed', () => {
  assert.match(headLine({ ...fixture.roles[0], company: 'AT&amp;T' }), /AT&amp;amp;T/);
  assert.match(headLine(fixture.roles[0]), /<span>AT&amp;T, 2021/);
});

test('a block whose role left the canon is reported', () => {
  const html = page([role('att', '<div class="career-head"></div>'), role('ge', '<div class="career-head"></div>'),
    role('gone', '<div class="career-head"><strong>Old</strong><span>Gone Co</span></div>')]);
  const r = applyCareer(html, fixture);
  assert.deepEqual(r.unknown, ['gone']);
  assert.ok(r.html.includes('<span>Gone Co</span>'));
});

test('missing markers throw', () => {
  assert.throws(() => applyCareer('<div class="career-list"></div>', fixture), /marker not found: CAREER FACTS/);
});

test('no salary and no em dash in the output', () => {
  const html = page([role('att', '<div class="career-head"></div>'), role('ge', '<div class="career-head"></div>')]);
  const out = applyCareer(html, fixture).html;
  assert.doesNotMatch(out, /190,000|230,000|\$\d/);
  assert.ok(!out.includes(EM_DASH));
});

test('missing canon exits 2 and writes nothing', () => {
  const before = statSync(join(root, 'index.html')).mtimeMs;
  const r = spawnSync('node', [join(root, 'scripts', 'sync-career.mjs')], { env: { ...process.env, CAREER_JSON: '/nonexistent/career.json' }, encoding: 'utf8' });
  assert.equal(r.status, 2);
  assert.match(r.stderr, /career\.json not found: \/nonexistent\/career\.json/);
  assert.equal(statSync(join(root, 'index.html')).mtimeMs, before);
});

test('index.html is in sync with career.json', { skip: !hasCanon && 'job-hunter data not present' }, () => {
  const html = readFileSync(join(root, 'index.html'), 'utf8');
  const r = applyCareer(html, JSON.parse(readFileSync(canonPath, 'utf8')));
  assert.deepEqual(r.missing, []);
  assert.equal(r.html, html, 'run node scripts/sync-career.mjs');
});
