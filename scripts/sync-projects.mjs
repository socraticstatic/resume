#!/usr/bin/env node
// Regenerate the Projects window rows and the per-project windows in index.html
// from the shared registry (../job-hunter/data/projects.json). A project shows a
// screenshot when assets/work/<id>.webp exists; a GitHub link when its repo is
// public; a Live link when it has one. Run after any registry change:
//   node scripts/sync-projects.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const registry = JSON.parse(readFileSync(join(root, '..', 'job-hunter', 'data', 'projects.json'), 'utf8'));
const esc = (t) => t.replace(/&(?!amp;|lt;|gt;|quot;|#)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const attr = (t) => esc(t).replace(/"/g, '&quot;');

const projects = registry.projects.filter((p) => p.surfaces && p.surfaces.retro);
const rows = [], wins = [];
for (const p of projects) {
  const id = 'proj-' + p.id;
  const when = `${p.org}, ${p.dates}`;
  const tags = p.tags.map((t) => `<span class="about-cap">${esc(t)}</span>`).join(' ');
  rows.push(
`          <div class="project-item" onclick="openWin('${id}')" data-when="${attr(when)}" data-stack="${attr(p.tags.join(', '))}" data-notes="${attr(p.summary)}">
            <div class="project-head"><strong>${esc(p.name)}</strong><span>${esc(when)}</span></div>
          </div>`);
  const shot = existsSync(join(root, 'assets', 'work', `${p.id}.webp`)) ? `        <img class="pw-shot" src="assets/work/${p.id}.webp" alt="${attr(p.name)}">\n` : '';
  const links = [];
  if (p.links.repo && p.visibility === 'public') links.push(`<a class="career-pill" href="${attr(p.links.repo)}" target="_blank" rel="noopener">GitHub</a>`);
  if (p.links.live) links.push(`<a class="career-pill" href="${attr(p.links.live)}" target="_blank" rel="noopener">Live site</a>`);
  wins.push(
`    <div class="window project-window" id="win-${id}" style="width:540px; height:auto; max-height:90vh;">
      <div class="titlebar" onmousedown="startDrag(event, '${id}')">
        <div class="closebox" onclick="closeWin('${id}')"></div>
        <div class="titlebar-lines"></div>
        <div class="titlebar-title">${esc(p.name)}</div>
      </div>
      <div class="win-body pw-body">
${shot}        <div class="pw-meta"><span>${esc(p.org)}</span><span>${esc(p.dates)}</span></div>
        <p class="pw-summary">${esc(p.summary)}</p>
        <div class="project-tags">${tags}</div>
${links.length ? `        <div class="pw-links">${links.join(' ')}</div>\n` : ''}      </div>
      <div class="win-resize" onmousedown="startResize(event, '${id}')"></div>
    </div>`);
}

let html = readFileSync(join(root, 'index.html'), 'utf8');
const a = html.indexOf('<div class="project-list">');
const b = html.indexOf('<div class="win-status" data-count="project-item">');
if (a < 0 || b < 0) throw new Error('project-list markers not found');
html = html.slice(0, a) + '<div class="project-list">\n' + rows.join('\n') + '\n        </div>\n      </div>\n      ' + html.slice(b);

const START = '    <!-- PROJECT WINDOWS (generated by scripts/sync-projects.mjs from the registry; do not edit by hand) -->\n';
const END = '    <!-- /PROJECT WINDOWS -->\n';
const block = START + wins.join('\n') + '\n' + END;
const s = html.indexOf(START), e = html.indexOf(END);
if (s >= 0 && e >= 0) html = html.slice(0, s) + block + html.slice(e + END.length);
else {
  const t = html.indexOf('    <!-- Themes -->');
  if (t < 0) throw new Error('Themes marker not found');
  html = html.slice(0, t) + block + '\n' + html.slice(t);
}
writeFileSync(join(root, 'index.html'), html);
console.log(`synced ${projects.length} projects (${wins.filter((w) => w.includes('pw-shot')).length} with screenshots)`);
